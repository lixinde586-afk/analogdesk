/**
 * AnalogDesk - complete research task runner.
 *
 *   npm run demo                 runs the default task and writes demo/
 *   node scripts/run-demo.mjs --symbol BABA --horizon 5 --question "..."
 *
 * Track 3 (AI Trading Desk) requires ONE complete research task: question -> actionable insight,
 * and the submission rules require the report to ship with the code that generated it rather than
 * as screenshots. This script is that code. It runs the real engine - the same createDesk() that
 * server.mjs and the static bundle use - and writes:
 *
 *   demo/run-record.json   the full machine-readable record: the question, the frozen engine
 *                          config, the complete research card, the narrative with its numeric-gate
 *                          result, every stress scenario, and the out-of-sample validation
 *   demo/RUN-RECORD.md     the human-readable version of the same run, for the form and the video
 *
 * Nothing in either file is hand-written. Every figure comes from the engine payload, and the
 * narrative is re-checked by src/llm/verify-numbers.mjs before it is written; if the gate rejects
 * it, the run fails loudly instead of publishing prose containing an unsupported number.
 */

