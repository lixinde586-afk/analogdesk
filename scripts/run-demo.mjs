const DEFAULT_QUESTION =
  "NVDA is at its 52-week-high area after a strong run. Before I open a position, what did the " +
  "historical episodes that most resemble this state actually do over the next trading week, and " +
  "how bad does the path get in the scenarios I should be worried about?";

function parseArgs(argv) {
  const a = { symbol: "NVDA", horizon: DEFAULT_HORIZON, k: DEFAULT_K, date: "latest", question: DEFAULT_QUESTION, language: null, stress: true };
  for (let i = 0; i < argv.length; i++) {
    const k = argv[i], v = argv[i + 1];
    if (k === "--symbol" || k === "-s") { a.symbol = String(v).toUpperCase(); i++; }
    else if (k === "--horizon" || k === "-H") { a.horizon = Number(v); i++; }
    else if (k === "--k" || k === "-k") { a.k = Number(v); i++; }
    else if (k === "--date" || k === "-d") { a.date = String(v); i++; }
    else if (k === "--question" || k === "-q") { a.question = String(v); i++; }
    else if (k === "--language" || k === "-l") { a.language = String(v); i++; }
    else if (k === "--no-stress") { a.stress = false; }
    else if (k === "--help" || k === "-h") { log("usage: node scripts/run-demo.mjs [--symbol NVDA] [--horizon 5] [--k 50] [--date latest] [--question \"...\"] [--language en|zh] [--no-stress]"); process.exit(0); }
  }
  return a;
}

